export type LocalidadeTipo = "bairro" | "cidade";

export interface RegionalSeedItem {
  ordem: number;
  nome: string;
  slug: string;
  localidades: {
    nome: string;
    slug: string;
    tipo: LocalidadeTipo;
  }[];
}

export function slugifyRegionalText(text: string): string {
  return (text || "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

function buildLocalidades(names: string[], defaultTipo: LocalidadeTipo, overrides: Record<string, LocalidadeTipo> = {}) {
  return names.map((nome) => ({
    nome,
    slug: slugifyRegionalText(nome),
    tipo: overrides[nome] || defaultTipo,
  }));
}

